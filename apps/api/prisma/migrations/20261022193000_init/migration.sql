CREATE FUNCTION helpdesk_reject_history_update() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'append-only history cannot be updated'
    USING ERRCODE = '42501';
END;
$$;

CREATE FUNCTION helpdesk_reject_history_delete() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF current_setting('helpdesk.purge', true) IS DISTINCT FROM 'on' THEN
    RAISE EXCEPTION 'append-only history cannot be deleted'
      USING ERRCODE = '42501';
  END IF;
  RETURN OLD;
END;
$$;

CREATE FUNCTION helpdesk_reject_immutable_ticket_text() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.subject IS DISTINCT FROM OLD.subject
     OR NEW.description IS DISTINCT FROM OLD.description THEN
    RAISE EXCEPTION 'subject and description are immutable'
      USING ERRCODE = '42501';
  END IF;
  RETURN NEW;
END;
$$;

CREATE TABLE users (
  id uuid PRIMARY KEY DEFAULT helpdesk_uuidv7(),
  email citext NOT NULL UNIQUE,
  display_name text NOT NULL,
  role user_role NOT NULL,
  password_hash text NOT NULL,
  password_changed_at timestamptz NOT NULL DEFAULT now(),
  must_change_password boolean NOT NULL DEFAULT false,
  is_active boolean NOT NULL DEFAULT true,
  mfa_required boolean NOT NULL DEFAULT false,
  locked_until timestamptz,
  last_login_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT users_email_lower CHECK (email::text = lower(email::text))
);

CREATE TABLE sessions (
  id uuid PRIMARY KEY DEFAULT helpdesk_uuidv7(),
  user_id uuid NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
  token_hash bytea NOT NULL UNIQUE,
  client_type client_type NOT NULL,
  auth_methods text NOT NULL,
  mfa_verified_at timestamptz,
  idle_expires_at timestamptz NOT NULL,
  absolute_expires_at timestamptz NOT NULL,
  revoked_at timestamptz,
  ip inet,
  user_agent text
);
CREATE INDEX sessions_user_id_idx ON sessions (user_id);

CREATE TABLE user_mfa_factors (
  id uuid PRIMARY KEY DEFAULT helpdesk_uuidv7(),
  user_id uuid NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
  type mfa_factor_type NOT NULL,
  secret_encrypted bytea,
