CREATE TABLE products (
  id uuid PRIMARY KEY DEFAULT helpdesk_uuidv7(),
  name text NOT NULL UNIQUE,
  is_active boolean NOT NULL DEFAULT true,
  sort_order integer NOT NULL
);

CREATE TABLE tickets (
  id uuid PRIMARY KEY DEFAULT helpdesk_uuidv7(),
  reference text NOT NULL UNIQUE,
  product_id uuid NOT NULL REFERENCES products (id) ON DELETE RESTRICT,
  customer_email citext NOT NULL,
  customer_name text,
  subject text NOT NULL,
  description text NOT NULL,
  impact ticket_impact,
  status ticket_status NOT NULL,
  priority ticket_priority NOT NULL DEFAULT 'normal',
  assignee_id uuid REFERENCES users (id) ON DELETE RESTRICT,
  assigned_at timestamptz,
  first_accepted_by_id uuid REFERENCES users (id) ON DELETE RESTRICT,
  first_accepted_at timestamptz,
  needs_attention boolean NOT NULL,
  needs_attention_reason text,
  resolved_at timestamptz,
  auto_close_due_at timestamptz,
  closed_at timestamptz,
  cancelled_at timestamptz,
  email_confirmed_at timestamptz,
  email_thread_message_id text,
  privacy_ack_at timestamptz,
  privacy_notice_version text,
  context jsonb,
  version integer NOT NULL DEFAULT 0,
  search_vector tsvector GENERATED ALWAYS AS (
    to_tsvector(
      'english',
      coalesce(subject, '') || ' ' || coalesce(description, '') || ' ' || coalesce(customer_name, '')
    )
  ) STORED,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT tickets_email_lower CHECK (customer_email::text = lower(customer_email::text)),
  CONSTRAINT tickets_subject_length CHECK (char_length(subject) BETWEEN 1 AND 150),
  CONSTRAINT tickets_description_length CHECK (char_length(description) BETWEEN 1 AND 10000),
  CONSTRAINT tickets_customer_name_length CHECK (
    customer_name IS NULL OR char_length(customer_name) <= 100
  ),
  CONSTRAINT tickets_reference_shape CHECK (
    reference ~ '^HD-[23456789ABCDEFGHJKMNPQRSTVWXYZ]{6}$'
  ),
  CONSTRAINT tickets_version_nonnegative CHECK (version >= 0)
);
CREATE INDEX tickets_product_id_idx ON tickets (product_id);
CREATE INDEX tickets_assignee_id_idx ON tickets (assignee_id);
CREATE INDEX tickets_first_accepted_by_id_idx ON tickets (first_accepted_by_id);
CREATE INDEX tickets_customer_email_idx ON tickets (customer_email);
CREATE INDEX tickets_search_vector_idx ON tickets USING GIN (search_vector);
-- M1-T09 counts flagged tickets. The partial index is created with the schema
-- so that task does not need its own migration.
CREATE INDEX tickets_needs_attention_idx ON tickets (id) WHERE needs_attention;

CREATE TRIGGER tickets_immutable_text
  BEFORE UPDATE ON tickets
  FOR EACH ROW EXECUTE FUNCTION helpdesk_reject_immutable_ticket_text();

CREATE TABLE ticket_messages (
  id uuid PRIMARY KEY DEFAULT helpdesk_uuidv7(),
  ticket_id uuid NOT NULL REFERENCES tickets (id) ON DELETE CASCADE,
  author_type author_type NOT NULL,
  author_user_id uuid REFERENCES users (id) ON DELETE RESTRICT,
  visibility message_visibility NOT NULL,
  body text NOT NULL,
  search_vector tsvector GENERATED ALWAYS AS (
    to_tsvector('english', coalesce(body, ''))
  ) STORED,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ticket_messages_body_present CHECK (char_length(body) >= 1)
);
CREATE INDEX ticket_messages_ticket_id_idx ON ticket_messages (ticket_id);
CREATE INDEX ticket_messages_author_user_id_idx ON ticket_messages (author_user_id);
CREATE INDEX ticket_messages_search_vector_idx ON ticket_messages USING GIN (search_vector);

CREATE TRIGGER ticket_messages_append_only_update
  BEFORE UPDATE ON ticket_messages
  FOR EACH ROW EXECUTE FUNCTION helpdesk_reject_history_update();
CREATE TRIGGER ticket_messages_append_only_delete
  BEFORE DELETE ON ticket_messages
  FOR EACH ROW EXECUTE FUNCTION helpdesk_reject_history_delete();

